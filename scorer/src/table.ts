import type { MasbResult } from "./types.js";

const f1 = (n: number) => n.toFixed(1);
const pct = (n: number) => `${Math.round(n * 100)}%`;
const sim = (n: number | null) => (n === null ? "n/a" : n.toFixed(3));

/** Render RESULTS.md from a set of result files. */
export function renderTable(results: MasbResult[]): string {
  const sorted = [...results].sort((a, b) => a.room.localeCompare(b.room) || b.scores.consistency - a.scores.consistency);
  const lines: string[] = [
    "# MASB results",
    "",
    `Benchmark version ${results[0]?.version ?? "0.1.0"}. Generated by \`masb table\` from \`results/\`. Consistency = mean(inventory, identity, placement). Realism and architecture preserved are reported separately. CLIP similarity is a secondary, non-judged number. See PROTOCOL.md.`,
    "",
  ];

  const systems = [...new Set(sorted.map((r) => r.system))];
  const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / xs.length;
  lines.push(
    "## By system (mean over rooms)",
    "",
    "| System | Rooms | Consistency | Inventory | Identity | Placement | Realism | Arch. preserved |",
    "|---|---:|---:|---:|---:|---:|---:|---:|",
  );
  const bySystem = systems
    .map((s) => {
      const rs = sorted.filter((r) => r.system === s);
      return { s, rs, c: mean(rs.map((r) => r.scores.consistency)) };
    })
    .sort((a, b) => b.c - a.c);
  for (const { s, rs, c } of bySystem) {
    lines.push(
      `| ${s} | ${rs.length} | ${f1(c)} | ${f1(mean(rs.map((r) => r.scores.inventory_agreement)))} | ${f1(mean(rs.map((r) => r.scores.identity_agreement)))} | ${f1(mean(rs.map((r) => r.scores.placement_agreement)))} | ${f1(mean(rs.map((r) => r.scores.realism)))} | ${pct(mean(rs.map((r) => r.scores.architecture_preserved_rate)))} |`,
    );
  }

  lines.push(
    "",
    "## By room",
    "",
    "| Room | Photos | System | Consistency | Inventory | Identity | Placement | Realism | Arch. preserved | CLIP sim. |",
    "|---|---:|---|---:|---:|---:|---:|---:|---:|---:|",
  );
  for (const r of sorted) {
    const s = r.scores;
    const flag = r.details.flags.no_shared_items ? " (no shared items)" : "";
    lines.push(
      `| ${r.room} | ${r.photos} | ${r.system} | ${f1(s.consistency)}${flag} | ${f1(s.inventory_agreement)} | ${f1(s.identity_agreement)} | ${f1(s.placement_agreement)} | ${f1(s.realism)} | ${pct(s.architecture_preserved_rate)} | ${sim(s.identity_embedding_similarity)} |`,
    );
  }
  const judges = [...new Set(results.map((r) => `${r.judge.model} (median of ${r.judge.runs})`))];
  lines.push("", `Judge: ${judges.join(", ") || "n/a"}.`, "");
  return lines.join("\n");
}
